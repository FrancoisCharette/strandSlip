$DEBUG
$NOFLOATCALLS
$STORAGE:2
C
      PROGRAM FRICTION
C
C  CE PROGRAMME CALCUL LE COEFFICIENT DE FRICTION EN FONCTION
C  DE `X', SELON L'EQUATION 19 DU RAPPORT DE PROJET-1. IL 
C  UTILISE LE FICHIER "ENTRE.DAT" POUR OBTENIR LES DONNE DE
C  DEPART.
C
      IMPLICIT DOUBLE PRECISION (A-F)
      IMPLICIT DOUBLE PRECISION (P-X)
      DIMENSION THETA(50)
C
      OPEN(1,FILE='F_RESFIN.DAT',ACCESS='SEQUENTIAL',STATUS='NEW')
      OPEN(2,FILE='F_DONNE1.DAT',ACCESS='SEQUENTIAL',STATUS='NEW')
      OPEN(3,FILE='ENTRE.DAT',ACCESS='SEQUENTIAL',STATUS='OLD')
      UN=1D0
      PI=DACOS(-UN)
C
      READ(3,1) CL
      READ(3,2) NFIL
      THETA(1)=0 
      DO 100 I=2,NFIL
      M=I-1
      THETA(I)=THETA(M)+(2*PI)/NFIL
      WRITE(*,4) I,THETA(I)
  100 CONTINUE
    4 FORMAT(3X,I2,6X,F9.4)
      READ(3,1) ALPHA
      READ(3,1) RT
      READ(3,1) ET
      READ(3,1) TI
      READ(3,1) RN
      READ(3,1) EN
      READ(3,1) CPN
      READ(3,1) CFL
      READ(3,1) WL
      READ(3,1) AMP
      READ(3,2) NPAS
      READ(3,1) XDEPART
      READ(3,1) XFINAL
    1 FORMAT(1X,D14.8)
    2 FORMAT(1X,I6)
C
C    FIN D ENTRE DES DONNEES
C
      DXPAS=CL/NPAS
      X=XDEPART
C
C   EQUATION 3
C
      F=(1-CPN*(DTAN(ALPHA))**2)*(DCOS(ALPHA))**2
C
C   La longueur du pas ce calcul avec l equation 13
C
      PITCH=(2*PI*RN)/DTAN(ALPHA)
C
C   L aire de la section du toron ce calcul de la facon suivante
C
      AT=PI*RT**2
C 
C   La pression d appuie se calcul selon l'equation 12.
C
      Q=(TI*(DSIN(ALPHA))**2)/RN
C
C  Ici on calcul le produit des constante de l'equation 19 
C
      CST9=((RN*AMP*F*ET*AT*DCOS(ALPHA))/Q)*((2*PI)/WL)**3
C
  119 DO 129 I=1,NFIL
      CA9=(WL/PITCH)*(DCOS((2*PI*X)/PITCH+THETA(I)))*(DSIN((2*PI*X)/WL))
      CB9=(DSIN((2*PI*X)/PITCH+THETA(I)))*(DCOS((2*PI*X)/WL))
      CFX=CST9*(CA9+CB9)
      WRITE(1,10) X,CFX,I
      WRITE(*,10) X,CFX,I
  129 CONTINUE
      X=X+DXPAS
      IF(X.LT.XFINAL) GOTO 119
C
      WRITE(2,40) AMP,RN,CPN
   40 FORMAT(2X,'AMPLITUDE=',E9.4,/,2X,'R. DU NOYEAU=',F5.3,/,2X,
     +'COEFFICIENT DE POISSON=',F5.3)
      WRITE(2,41) ALPHA,RT,ET
   41 FORMAT(2X,'ANGLE D ENROULEMENT=',F7.5,/,2X,'R. DU TORON=',E9.4,
     +/,2X,'MODULE DE YOUNG DU TORON=',E9.4)
      WRITE(2,42) WL,CL
   42 FORMAT(2X,'LONGUEUR D ONDE=',F5.2,
     +/,2X,'LONGUEUR DU CABLE=',F9.3)
      WRITE(2,43) CFL,PITCH
   43 FORMAT(2X,'COEFF. F=',F7.4,/,2X,
     +'PITCH=',F7.4)
      WRITE(2,44) AT,DXPAS,CST9
   44 FORMAT(2X,'AIRE DU TORON=',E9.4,/,2X,'INCREMENT EN X=',F9.5,
     +/,2X,'CONSTANTE EQ9=',E12.7)
      WRITE(2,45) NFIL,EN,F
   45 FORMAT(2X,'NOMBRE DE FIL:',I2,/,2X,'MOD. DE YOUG DU NOYEAU=',
     +E9.4,/,2X,'F SELON EQUATION 2b=',E9.4)
      WRITE(2,46) TI
   46 FORMAT(2X,'TENSION DANS LE FIL=',E9.4)
   10 FORMAT(3X,F9.4,3X,F12.7,3X,I3)
      CLOSE(3)
      CLOSE(2) 
      CLOSE(1)
      STOP
      END
